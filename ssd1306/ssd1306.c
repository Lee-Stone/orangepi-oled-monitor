/* ========== 底层 I2C ========== */
static void write_cmd(int fd, uint8_t cmd) {
    wiringPiI2CWriteReg8(fd, 0x00, cmd);
}
static void write_data(int fd, uint8_t data) {
    wiringPiI2CWriteReg8(fd, 0x40, data);
}

/* ========== 初始化 ========== */
int ssd1306_init(const char *i2c_dev) {
    int fd = wiringPiI2CSetupInterface(i2c_dev, SSD1306_I2C_ADDR);
    if (fd < 0) {
        fprintf(stderr, "ERROR: Cannot open %s @ 0x%02X\n", i2c_dev, SSD1306_I2C_ADDR);
        return -1;
    }

    uint8_t init_seq[] = {
        0xAE,       /* display off */
        0xD5, 0x80, /* clock div */
        0xA8, 0x1F, /* mux ratio: 32 */
        0xD3, 0x00, /* display offset */
        0x40,       /* start line */
        0x8D, 0x14, /* charge pump */
        0xA1,       /* segment remap */
        0xC8,       /* COM scan direction */
        0xDA, 0x00, /* COM pins config (0x00 = alternative) */
        0x81, 0x80, /* contrast */
        0xD9, 0x1F, /* pre-charge period */
        0xDB, 0x40, /* VCOMH deselect */
        0xA4,       /* resume to RAM */
        0xAF,       /* display on */
    };
    for (size_t i = 0; i < sizeof(init_seq); i++)
        write_cmd(fd, init_seq[i]);

    ssd1306_clear(fd);
    return fd;
}

void ssd1306_close(int fd) {
    if (fd >= 0) {
        write_cmd(fd, 0xAE);
    }
}

/* ========== 光标定位 ========== */
void ssd1306_set_pos(int fd, uint8_t x, uint8_t y) {
    write_cmd(fd, 0xB0 + y);
    write_cmd(fd, ((x & 0xF0) >> 4) | 0x10);
    write_cmd(fd, (x & 0x0F) | 0x00);
}

/* ========== 清屏 ========== */
void ssd1306_clear(int fd) {
    uint8_t i, j;
    for (i = 0; i < 4; i++) {
        write_cmd(fd, 0xB0 + i);
        write_cmd(fd, 0x00);
        write_cmd(fd, 0x10);
        for (j = 0; j < 128; j++)
            write_data(fd, 0x00);
    }
}

/* ========== 全白填充 ========== */
void ssd1306_fill(int fd) {
    uint8_t i, j;
    for (i = 0; i < 4; i++) {
        write_cmd(fd, 0xB0 + i);
        write_cmd(fd, 0x00);
        write_cmd(fd, 0x10);
        for (j = 0; j < 128; j++)
            write_data(fd, 0xFF);
    }
}

/* ========== 显示 6x8 字符 ========== */
void ssd1306_show_char(int fd, uint8_t x, uint8_t y, char ch) {
    uint8_t c = (uint8_t)ch - 32;
    if (c > 94) c = 0;

    ssd1306_set_pos(fd, x, y);
    uint8_t i;
    for (i = 0; i < 6; i++)
        write_data(fd, F6x8[c][i]);
}

/* ========== 显示字符串 ========== */
void ssd1306_show_str(int fd, uint8_t x, uint8_t y, const char *str) {
    while (*str) {
        ssd1306_show_char(fd, x, y, *str);
        x += 6;
        if (x > 122) { x = 0; y++; }
        if (y > 3) break;
        str++;
    }
}

